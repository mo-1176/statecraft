# 材料を読めるphase（初期構築と記憶の更新）に載せる、memoryへの書き起こしの規則。
#
# 「判断に必要な粒度で」「情報倉庫ではない」のような絞り込みの指示だけを置くと、
# モデルは「今の問いに直接答える1点」だけを残し、条件・例外・数値・隣接する対象を
# 落とす。材料はこの生成の後に消えるため、落としたものは回答の時点で存在しない。
