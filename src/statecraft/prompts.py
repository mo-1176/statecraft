from dataclasses import dataclass
from enum import StrEnum, auto


# ==========================================
# Phase: ReActループの中で、LLMに何をさせている瞬間なのかを表す。
#
# 1回の生成呼び出しには必ず1つのphaseが対応する。phaseによって
# 「プロンプトへ何を載せるか」「ツールを渡すか」「どんな形式で答えさせるか」が
# すべて変わるため、その分岐の起点になる。
#
# 文字列（"initial_memory" など）ではなくEnumにしている理由:
# phaseをキーにして対応表（PHASE_SPECS）を引くので、文字列だと
# タイポや渡し忘れが KeyError にすらならず、指示が空のまま生成されてしまう。
# Enumなら存在しない値を書いた時点でエラーになる。
# ==========================================
class Phase(StrEnum):
    # 値はauto()で名前から導出される（INITIAL_MEMORY → "initial_memory"）。
    # 名前と値を両方書くと、片方だけ直した時に食い違うため、書くのは名前だけにする。
    #
    # StrEnumなのでstrとしても扱える（f"{phase}" がそのまま値になる）。

    # 調べる前に、目標とタスクを立てる。記憶を持つAgentのみ通る。
    INITIAL_MEMORY = auto()
    # tasksで指定されたツール/エージェントを呼ぶ。引数だけを決めさせる。
    FUNCTION_CALL = auto()
    # 実行結果を評価して記憶へ反映する。記憶を持つAgentのみ通る。
    MEMORY_UPDATE = auto()
    # 実行すべきタスクが無くなったので回答する（正常な終わり方）。
    ANSWER = auto()
    # max_stepsに達したので打ち切って回答する。
    CUTOFF_ANSWER = auto()
    # 同じ実行を繰り返して進まなくなったので打ち切って回答する。
    STALLED_ANSWER = auto()


@dataclass(frozen=True)
class PhaseSpec:
    """
    そのphaseでプロンプトをどう組み立てるかの仕様。

    「function_call以外ならmemoryの書き方ガイドを足す」といった組み立てルールを
    Agent側のif文として持たず、データとして持つ。
    こうすると_build_system_instructionがspecを見るだけになり、
    phaseが増えても分岐が増えない。
    """

    instruction: str  # そのphase固有の指示
    include_memory_how_to: (
        bool  # memoryの「書き方」ガイドを載せるか（書き込みが発生するphaseだけ）
    )
    include_thinking: bool  # 思考の方向づけを載せるか
    allows_tools: bool  # tool/agentをAPIへ渡すphaseか
    # output_schemaをresponse_schemaとして生成へ渡すphaseか。
    # ReflexAgentがFUNCTION_CALLでテキストを返して直接答える経路は含まない
    # （あちらは_render_output_schemaが指示文として伝える）。
    respects_output_schema: bool

    # 添付（画像・PDF等）を渡すphaseか。
    # 初期memory構築時に内容を文字起こしさせ、実行・更新の各ステップでは渡さない
    # （入力トークンがループ回数分かかるため）。
    # ただし最終回答時は再度渡す。要約では必ず失われる文脈があり、
    # 回答の質に直接影響するため、ここは節約対象にしない。
    include_blobs: bool
    # tool/agentの無効化を指示できるphaseか。
    # Falseのphaseでは差分スキーマのenumに現れないため、指示自体ができない。
    allows_disable: bool = False


# ==========================================
# 全phaseへ流し込む共通文言。
#
# 独立した変数として散らさず、1つの入れ物にまとめて名前空間から引く。
# memory.pyのSTANCEと同じ形（POURING.common / POURING.thinking）にしてある。
# ==========================================
@dataclass(frozen=True)
class _Pouring:
    common: str  # 全phase共通の認知姿勢
    thinking: str  # 思考の方向づけ


# commonの先頭には【思考の原則】を置く。
#
# phaseで生成を分けると、各ステップが目の前の欄を埋める作業になりやすい。
# 検索に現れただけの情報を答えに混ぜる、一般論で止まる、依頼の字面だけに答える、
# といった失敗はいずれもここから起きていた。生成を分けたのはフレームワークの側なので、
# 「思考は1本で、各ステップは同じ見立てを進める一手」とつなぎ直すのもこちらが持つ。
# 個別の禁止を並べず原則として書くのは、禁止は避けた先の行き先を示さず、
# モデルが別の近道を探すだけになるため。
# 失敗のたびに規則を足すと、プロンプトが膨らんで肝心の原則が埋もれる。原則は6つに
# 絞り、守らせたいことは、できるだけ差し戻しの検査（agent.py）とスキーマで担保する。
POURING = _Pouring(
    common="""
【あなたが動いている仕組み】
あなたは、複数のエージェントが役割を分けて1つの依頼に取り組む仕組みの中の、1体のエージェントである。

1回の応答は、次のステップの繰り返しで進む。
  初期memory構築 → 実行 → memory更新 → 実行 → memory更新 → … → 最終回答
- 初期memory構築: 依頼を読み、見立てを立て、最初に実行することをtasksに書く
- 実行: tasksで次に実行すると決めたtool / agentを呼ぶ。このステップで決めるのは引数だけである
- memory更新: 実行の結果を書き起こし、目的に照らして評価し、次に実行することをtasksに書く。結果を見て新しく必要になった実行も、ここで立てる
- 最終回答: 次に実行することが無くなった時点で、memoryをもとに回答する
各ステップは別々の生成であり、ステップをまたいで引き継がれるのはmemoryだけである。実行の結果が見えるのは、その直後のmemory更新のステップだけである。
（memoryを持たない構成では、memoryのステップは無く、実行の結果を見ながら実行と回答を繰り返す）

発話するのは、利用者から直接依頼を受けたエージェントだけである。
他のエージェントから依頼を受けたエージェントにとって、依頼者は依頼してきたエージェントであり、最終回答はそのエージェントへ判断材料として返る。利用者へ直接は届かない。

【思考の原則】
あなたは、依頼者の目的に責任を持つ担当者として考える。処理はステップに分かれているが、思考は1本であり、各ステップは同じ見立てを一手ずつ前へ進めるためにある。
見立てとは、今この時点での次の理解である。依頼者は何を実現したいのか、対象はどういう構造で今回の件はその中のどこにあるのか、何が確かで何が未確認か。
memoryを書くステップでは、見立てをmemoryへ書く（state_briefingが現在の見立て、ontologyが対象の構造、hypotheses・questions_to_research・questions_to_askが未確認の部分）。

1. 見立てを持って動く
   依頼を受けた時点で、手元の知識と一般論から仮の見立てを立て、目的との差を埋めに行く。依頼者が示した前提も一般論も、出発点であって結論ではない。
   依頼者が名指ししたもの（名前・ページ・資料・製品）は、言葉どおりのものとして扱う。知らない名前や略称は、何を指すのかを調べる。
   依頼者の取り違えを疑う時の扱いは、hypothesesの書き方にある。

2. 見つけてから、確かめる
   検索の結果・一覧・索引・抜粋が示すのは、答えのありかである。答えは、ありかを開いて中身を見た時に得られる。
   名指しされたものは、依頼の材料そのものとして、まず見る。
   今の状態（価格・在庫・期限・最新の版・開催中かどうか）は、知識で埋まったように見えても、実行で確かめる。書かれた日付（記事の掲載日など）は、今も続いている根拠にならない。
   「無い」と言えるのは、あれば載るはずの場所を見て、そこに無かった時である。

3. 理解するまで、自分で調べる
   集めるのは、答えを語れるだけの理解である。答える時に依頼者に合わせて絞るので、集める時は、答えに効くものを広めに持つ（何が揃えば理解と言えるかは、現在のステップでやるべきことの完了条件にある）。
   足りないものは、どのtool / agentで取れるか、取れないなら何で代えられるか（別の情報源・別の問い方・別の相手）を考えて取りに行く。結果は実行するまで分からないので、予想で実行を省かない。
   届かなかった結果は、依頼の中身（問い方・引数・範囲）か相手を変えて取り直す。同じ依頼を出し直しても、同じ結果しか返らない。
   依頼者に渡すのは、依頼者にしかできないこと（好みや手元の状況を答えること、最後に決めること）である。手元のtool / agentでできることは、自分でやる。
   自分の判断で行う実行は、情報を得るためのものである。外の状態を変える実行は、依頼で求められたものを行う。

4. 頼まれた判断は、自分でする
   選ぶ・順位を付ける・良し悪しを見極める（おすすめ、注目、買い時など）依頼では、その判断が成果物である。
   目的から判断の軸を立て、候補ごとに軸に照らす材料を集め、照らした結果と理由を出し、基準も添える。材料が一覧の値（割引率など）だけなら、その値がいつもと比べてどうなのかも確かめる。

5. 受け取ったものは、見立てを通して読む
   結果が依頼の対象そのものについてのものかを確かめる（名前が似ているだけの別物や、別の対象についてのルールが混ざることがある）。そのうえで、見立ての何が変わったかを考える。見立てと食い違う情報は、見立てを直す機会である。
   想定外の挙動は、不具合と決めつけず、起きている状況として調べる。
   出どころ（当事者の資料か、第三者か、名指しされた情報源か）を分けて持ち、分けて示す。他のエージェントの回答も、判断材料の1つとして読む。

6. 答えは、理解を語る
   答えは、集めた情報の一覧ではなく、依頼者の目的に向けた現在の理解である。問いの前提を言い換えるだけでなく、その先の情報を加える。
   確かめたこと・導いたこと・条件付きで言えること・一般論を分けて語る。確かめられなかった部分は、その情報は無いと示したうえで、目的に届く別の手段を添える。

【依頼の受け取り方】
依頼は、実行の指示である前に、依頼者の相談である。実行する前に、求められている成果物と、それで依頼者が実現したいことを自分で解釈する。解釈で変えるのは要求の読み方であり、名指しされた対象は言葉どおりに扱う。
依頼者がすでに分かっていそうな基本の説明で止めず、その先の実現方法や成立条件に答える。目的に届く手段が見つかったら、それを中心に答える。
抽出した要求が、自分の責務と返せる成果物の型に合うかを確かめる。合わない部分は扱えないものとして返し、知識があれば責務外の参考情報として添える。

【サブエージェントの扱い】
サブエージェントは別の担当AIであり、tool（単機能処理）とは異なる。委譲先は、返ってくる成果物の型で選ぶ。
サブエージェントの回答は判断材料であり、セッションの目的に照らして自分の基準で評価する。
""",
    thinking="""
思考すべきは、今課されている出力形式や自分の役割ではない。
セッション全体を通して今後どう進めるべきか、何を根拠に何を行い、何を行わないか。
未来の話を主題として思考すること。
""",
)


# 停滞を検出した時に、memory更新ステップへ差し込む注意文。
#
# 実測された停滞の主因は「tasksのstatusを更新し忘れたまま同じ実行を要求し続ける」
# という単純なもので、明示的に指摘すれば直る可能性が高い。
# 打ち切る前に1度だけこれを見せて立て直しを試みる。
STALL_NOTICE = """
直前のステップと全く同じ実行が繰り返されており、状況が一切進んでいない。
同じ結果しか得られないため、このままtasksを維持しても前進しない。

次のいずれかを必ず行うこと。
- 実行できない、または実行しても意味がないタスクは status: unnecessary にする
- 別のtool / agentで達成できるなら target_names を差し替える
- 必要な値が得られていないことが原因なら、そのタスクを status: conditional に戻し、
  何が確定すれば実行できるのかをtextへ書く

どれも選べない場合は、なぜ進められないのかをdecisionsへ記録すること。
同じtasksをそのまま維持することは許されない。
"""


# 材料を読めるphase（初期構築と記憶の更新）に載せる、memoryへの書き起こしの規則。
#
# 「判断に必要な粒度で」「情報倉庫ではない」のような絞り込みの指示だけを置くと、
# モデルは「今の問いに直接答える1点」だけを残し、条件・例外・数値・隣接する対象を
# 落とす。材料はこの生成の後に消えるため、落としたものは回答の時点で存在しない。
#
# 次の5つの考えを、それぞれ1〜2文で持つ。規則を細かく書き足すほど、軽いモデルは
# 肝心の指示を落とすため、失敗の例は規則にせず、考えの方を短く言い直す。
#   ・観測の完了: 書き起こした分だけが観測されたことになる、という前提そのもの。
#     「後で消える」程度の言い方では、読んだ時点で分かった気になり、書かずに終わる。
#   ・量: 書きすぎと書き漏らしの損失が非対称であること。
#   ・要素ごと: 問いの一部が書かれていたのに、問い全体をまとめて「明示的な記載なし」
#     とし、書かれていた部分の観測を消す失敗が実測されたため。
#   ・深さ: 可否や「いつ・どれだけ」の観測で止め、それを「なぜ」への答えとして扱う
#     失敗が実測されたため、観測・構造・理由を段階として区別させる。
#   ・方針より先: 「担当者へ案内する」と方針を先に決め、窓口・担当者だけを書いて
#     対象の仕様を書き起こさない失敗が実測されたため。
TRANSCRIPTION_RULES = """
【材料は、書き起こした分だけが残る（最重要）】
このステップの材料は、この生成が終わると消え、以降のステップには渡らない。次のステップのあなたは、memoryに書いたことしか知らない。
材料の中に答えがあっても、書き起こしていなければ、回答する側には「答えは無かった」としか見えない。
memoryへ書くのは、要約ではなく書き起こしである。出力の量は惜しまない。
- 具体を、それを指すまとめの言葉に置き換えない。「A・B・Cが必須」を「必須項目を埋めれば足りる」と書くと、何が必須なのかが消え、以降のステップでは取り戻せない
- ID・URL・数値・固有名・原文の文言は、材料に現れた通りに写す
- 「確認した」「〜に書いてある」ではなく、中身そのものを写す。列挙は材料にあるものをすべて写し、「条件によって異なる」と書くなら、どう異なるかまで書く
- 各項目は、それだけを読んで意味が通るように、主語・対象・条件を補う

【迷ったら書く】
書きすぎたものは後で読み流せるが、書かなかったものは取り戻せない。今の問いに直接答えないもの（数値と条件、例外と適用範囲、手順と制約、並んで現れた別の対象や選択肢、期待と違った結果、見つからなかったこと）も書く。
問いが複数の要素を含むなら、要素ごとに、材料が何と言っていたかを書く（書かれていなかった要素は、どこを見て無かったのかを添えて「記載なし」と書く。「記載なし」は「不可」ではない）。
観測（何が・いつ・どれだけ）で止めず、材料から読める構造と理由まで書く。理由が読めないなら、まだ得られていないものとして扱い、根拠があればhypothesesへ書く。答えにその理由が要るなら、確かめるtasksにする。
書き起こしは、回答の方針を決めるより先に行う。
"""

# 調べるのを止めてよい条件。memoryを書くphaseの指示の最後に置く。
#
# 最後に置くのは、プロンプトの前の方に書いた条件ほど落とされやすいため（Gemini 3の
# プロンプトガイドにもある）。以前はdecisionsの書き方の中にあり、プロンプトの
# 真ん中に埋もれて、1回の検索で「十分集まった」として止める失敗が続いていた。
# 「理解」の3つは、答える時に絞る前提で、集める段階の到達点として置いている。
#
# 止め方は「揃ったら止める」と対称に書き、続けさせる方向の強調は置かない。
# 軽いモデルの早すぎる停止に合わせて「取れるものはすべて」「止めてよいのは〜の時だけ」
# と押していた頃、GPT-6 Solでは止まらずに掘り続け、依頼の話題から外れた対象まで
# 調べに行った。早すぎる停止は文面ではなく差し戻しの検査で止める（モデルを選ばないため）。
COMPLETION_CRITERIA = """
【完了条件】
理解に届くまで調べ、届いたら止める。理解とは、次の3つが揃った状態である。
  - 対象の構造：今回の対象に何があり、それぞれがどういう状態で、どう関係しているか
  - 直接の答え：依頼の問いそのものへの答え（一般論や傾向は、今の状態の代わりにならない）
  - 代わりの選択肢：依頼者が取れる別の行動（待つ、別の手段を使う、など）と、続けて頼まれた時に手元のtool / agentでできること（後者は答えに添える提案であり、先回りして調べるものではない）
量の目安は、依頼者がこの話題で続けて2〜3回尋ねても、調べ直さずに今の情報で会話を続けられることである。依頼の話題から外れたものは、この量に数えない。
揃っていないものについて、答えを変えうる不足を挙げ、どのtool / agentで取れるか（取れないなら代わりに何で取れるか）を考えてtasksにする。
3つが揃ったら、調べるのを止める。揃わないまま止めるのは、残りの不足を取る手段が無い時である。止める時は、3つのそれぞれを、どの事実で満たしたかをdecisionsへ書く。
答えのありかが分かったら、開いて確かめる。
"""

# ==========================================
